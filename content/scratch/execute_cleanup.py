def is_blacklisted(name):
    if name in EXPLICIT_REMOVALS:
        return True, "explicit_removal"
        
    if len(name) == 4:
        if any(name.startswith(p) for p in EFF_PREFIXES) or any(name.endswith(s) for s in EFF_SUFFIXES):
            return True, "efficacy_4"
            
    if len(name) >= 5:
        if any(name.startswith(p) for p in EFF_PREFIXES) and any(name.endswith(s) for s in EFF_SUFFIXES):
            return True, "efficacy_long"

    return False, None

