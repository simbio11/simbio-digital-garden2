# 1. Update MOC
moc_path = r'c:\Simbio\2. 약리 공부\처방\00_처방_학술_임상_MOC.md'
with open(moc_path, 'r', encoding='utf-8') as f:
    moc = f.read()

# 서경탕, 대진교탕 into 치풍·거풍제
if '[[서경탕]]' not in moc:
    moc = moc.replace('- [[견정산]]', '- [[견정산]]\n  - [[서경탕]]\n  - [[대진교탕]]')

# 과루해백백주탕 into 이기·화해제
if '[[과루해백백주탕]]' not in moc:
    moc = moc.replace('- [[지실해백계지탕]]', '- [[지실해백계지탕]]\n  - [[과루해백백주탕]]')

# 오피음 into 화담·거습·이수제
if '[[오피음]]' not in moc:
    moc = moc.replace('- [[택사탕]]', '- [[택사탕]]\n  - [[오피음]]')

# 통유탕 into 보익제
if '[[통유탕]]' not in moc:
    moc = moc.replace('- [[보양환오탕]]', '- [[보양환오탕]]\n  - [[통유탕]]')

# 한다열소탕 into 사상의학
if '[[한다열소탕]]' not in moc:
    if '사상의학' in moc:
        moc = moc.replace('## 사상의학', '## 사상의학\n- [[한다열소탕]]')
    else:
        moc = moc.strip() + '\n\n## 09. 사상의학 처방\n- [[한다열소탕]]\n'

with open(moc_path, 'w', encoding='utf-8') as f:
    f.write(moc)
print('MOC updated successfully')

